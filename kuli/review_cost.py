"""Slop, defined as an asymmetry, and therefore measurable.

The useful definition of slop is not "bad code". It is **work that costs far
less to produce than it costs to review**. Generating a thousand-line change
now costs almost nothing; reading one costs exactly what it always did.

That is a ratio, so it can be measured. The budget is added lines per
acceptance criterion the change claims to serve. A thousand lines serving one
criterion is slop by arithmetic, whatever it contains.

A change over budget is **split, not waved through**. The owner's attention is
the scarcest resource in the system, and this is the gate that protects it.

When a project declares no criteria, this gate reports that it is not
configured and does not fail. A gate that invents a verdict it cannot support
is worse than one that abstains and says so.
"""

import re
import subprocess

#: An identifier as used across these projects: A4.4, I2, R5, C2.1.
IDENTIFIER = re.compile(r"\b([ABCIR]\d+(?:\.\d+)?)\b")

#: Files whose size says nothing about review effort.
GENERATED_HINTS = (
    "AUTO-GENERATED", "DO NOT EDIT", "@generated", "generated by",
)


def git(args, root="."):
    result = subprocess.run(
        ["git"] + args, cwd=root, capture_output=True, text=True,
    )
    if result.returncode != 0:
        # First line only. git prints its whole usage on a bad invocation, and
        # a wall of help text buries the one sentence that says what is wrong.
        first = (result.stderr.strip().splitlines() or ["git failed"])[0]
        raise RuntimeError(first)
    return result.stdout


def changed_files(base, root="."):
    out = git(["diff", "--numstat", base + "...HEAD"], root)
    files = []
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) != 3 or parts[0] == "-":
            continue  # binary
        files.append({"added": int(parts[0]), "removed": int(parts[1]),
                      "path": parts[2]})
    return files


def is_generated(path, root="."):
    try:
        with open("%s/%s" % (root, path), encoding="utf-8") as handle:
            head = handle.read(2000)
    except (OSError, UnicodeDecodeError):
        return False
    return any(hint in head for hint in GENERATED_HINTS)


def claimed_identifiers(base, root="."):
    """Identifiers appearing in the diff body or in the commit subjects."""
    body = git(["diff", "--unified=0", base + "...HEAD"], root)
    subjects = git(["log", "--format=%s%n%b", base + "...HEAD"], root)
    found = set(IDENTIFIER.findall(body)) | set(IDENTIFIER.findall(subjects))
    return sorted(found)


def run(base, root=".", budget=120):
    """Returns (ok, report). ok is None when the gate cannot judge."""
    files = changed_files(base, root)
    reviewable = [f for f in files if not is_generated(f["path"], root)]
    added = sum(f["added"] for f in reviewable)
    generated = sum(f["added"] for f in files) - added
    identifiers = claimed_identifiers(base, root)

    report = {
        "base": base,
        "added_lines": added,
        "generated_lines_excluded": generated,
        "files": len(reviewable),
        "identifiers": identifiers,
        "budget_per_identifier": budget,
    }

    if not identifiers:
        report["note"] = (
            "No acceptance-criterion identifiers found in this change. This "
            "gate abstains rather than guessing a verdict it cannot support."
        )
        return None, report

    allowed = budget * len(identifiers)
    report["allowed"] = allowed
    report["ratio"] = round(added / len(identifiers), 1)
    if added > allowed:
        report["verdict"] = (
            "%d added lines for %d criteria is %d per criterion, over the "
            "budget of %d. Split this change." % (
                added, len(identifiers), report["ratio"], budget)
        )
        return False, report
    return True, report
